using DoneToday.Api.Data;
using DoneToday.Api.Entities;
using Microsoft.AspNetCore.DataProtection;
using Microsoft.AspNetCore.Identity;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;

namespace DoneToday.Api.Services;

public sealed class ProtectedUserStore(AppDbContext database, IDataProtectionProvider protection, IdentityErrorDescriber errors)
    : UserStore<User, IdentityRole<int>, AppDbContext, int>(database, errors)
{
    private const string Prefix = "protected:v1:";
    private static bool Sensitive(string provider, string name) => provider == "[AspNetUserStore]" && name is "AuthenticatorKey" or "RecoveryCodes";
    private IDataProtector Protector(int userId, string name) => protection.CreateProtector("DoneToday.IdentityTokens.v1", userId.ToString(System.Globalization.CultureInfo.InvariantCulture), name);

    public override Task SetTokenAsync(User user, string loginProvider, string name, string? value, CancellationToken cancellationToken = default) =>
        base.SetTokenAsync(user, loginProvider, name, value is not null && Sensitive(loginProvider, name)
            ? Prefix + Protector(user.Id, name).Protect(value) : value, cancellationToken);

    public override async Task<string?> GetTokenAsync(User user, string loginProvider, string name, CancellationToken cancellationToken = default)
    {
        var value = await base.GetTokenAsync(user, loginProvider, name, cancellationToken);
        if (value is null || !Sensitive(loginProvider, name)) return value;
        // Legacy rows are converted before the application starts accepting requests.
        if (!value.StartsWith(Prefix, StringComparison.Ordinal)) throw new InvalidOperationException("Identity token protection must run before serving requests.");
        return Protector(user.Id, name).Unprotect(value[Prefix.Length..]);
    }

    public async Task ProtectExistingAsync(CancellationToken cancellationToken = default)
    {
        var tokens = await Context.UserTokens.AsNoTracking().Where(token => token.LoginProvider == "[AspNetUserStore]" &&
            (token.Name == "AuthenticatorKey" || token.Name == "RecoveryCodes") && token.Value != null && !token.Value.StartsWith(Prefix)).ToListAsync(cancellationToken);
        foreach (var token in tokens)
        {
            var encrypted = Prefix + Protector(token.UserId, token.Name).Protect(token.Value!);
            // Do not overwrite a token regenerated by a concurrent request or another startup.
            await Context.UserTokens.Where(current => current.UserId == token.UserId && current.LoginProvider == token.LoginProvider &&
                current.Name == token.Name && current.Value == token.Value).ExecuteUpdateAsync(update => update.SetProperty(current => current.Value, encrypted), cancellationToken);
        }
    }
}
